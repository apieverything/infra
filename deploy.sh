#!/usr/bin/env bash
# ============================================================================
# API Everything — one-command local deployment.
#
#   ./deploy.sh              # build + start everything (default: up)
#   ./deploy.sh up           # same
#   ./deploy.sh down         # stop and remove containers (keeps the key DB)
#   ./deploy.sh status       # health of gateway, connectors and site
#   ./deploy.sh key          # create a 16-digit key (shown once, stdout = key only)
#   ./deploy.sh voucher      # issue a prepaid voucher (stdout = code only)
#   ./deploy.sh logs         # follow all logs
#   ./deploy.sh urls         # print endpoints
#   ./deploy.sh check        # lint every CI workflow shell block
#
# Overrides: WEB_PORT, CORE_PORT, CORE_STARTER_CREDITS.
#
# The stack mirrors production: only the gateway and the site are exposed.
# Clients reach connectors through the gateway with their 16-digit key.
# ============================================================================
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
STATE="$ROOT/.deploy"
COMPOSE=(docker compose --env-file "$STATE/.env" -f "$ROOT/docker-compose.yml" -p api-everything)

RED='' ; GREEN='' ; YELLOW='' ; DIM='' ; RST=''
if [[ -t 1 && -z "${NO_COLOR:-}" ]]; then
  RED=$'\033[31m'; GREEN=$'\033[32m'; YELLOW=$'\033[33m'; DIM=$'\033[2m'; RST=$'\033[0m'
fi
ok()   { printf '  %sOK%s %s\n' "$GREEN" "$RST" "$1"; }
info() { printf '  %s>%s %s\n' "$DIM" "$RST" "$1"; }
warn() { printf '  %s!%s %s\n' "$YELLOW" "$RST" "$1"; }
die()  { printf '\n  %sFAIL: %s%s\n\n' "$RED" "$1" "$RST" >&2; exit 1; }

need() { command -v "$1" >/dev/null 2>&1 || die "'$1' is required but not installed."; }

# Reuse the ports chosen at first deploy, unless overridden in the environment.
if [[ -f "$STATE/.env" ]] && [[ -z "${WEB_PORT:-}" ]]; then
  WEB_PORT="$(grep '^WEB_PORT=' "$STATE/.env" | cut -d= -f2-)"
fi
if [[ -f "$STATE/.env" ]] && [[ -z "${CORE_PORT:-}" ]]; then
  CORE_PORT="$(grep '^CORE_PORT=' "$STATE/.env" | cut -d= -f2-)"
fi
WEB_PORT="${WEB_PORT:-8180}"
CORE_PORT="${CORE_PORT:-9100}"
CORE_STARTER_CREDITS="${CORE_STARTER_CREDITS:-100}"
GATEWAY="http://localhost:$CORE_PORT"
SITE="http://localhost:$WEB_PORT"

clone_if_missing() {
  local dir="$1" repo="$2"
  [[ -d "$ROOT/$dir/.git" ]] && return
  [[ -d "$ROOT/$dir" ]] && return
  info "cloning apieverything/$repo..."
  git clone --depth 1 "https://github.com/apieverything/$repo.git" "$ROOT/$dir" >/dev/null 2>&1 \
    || die "cannot clone apieverything/$repo — clone it manually into $ROOT/$dir."
}

admin_token() {
  [[ -f "$STATE/.env" ]] || { printf ''; return; }
  grep '^CORE_ADMIN_TOKEN=' "$STATE/.env" | cut -d= -f2-
}

prepare() {
  mkdir -p "$STATE"
  need docker
  need node
  docker compose version >/dev/null 2>&1 || die "docker compose v2 is required."
  clone_if_missing connectors connectors
  clone_if_missing core core
  clone_if_missing web web

  # Generate once, so the admin token and key database stay stable across runs.
  if [[ ! -f "$STATE/.env" ]]; then
    local token
    token="$(node -e 'console.log(require("crypto").randomBytes(24).toString("hex"))')"
    cat > "$STATE/.env" <<EOF
# Generated by ./deploy.sh - do not commit. Contains a local admin token.
WEB_PORT=$WEB_PORT
CORE_PORT=$CORE_PORT
CORE_ADMIN_TOKEN=$token
CORE_STARTER_CREDITS=$CORE_STARTER_CREDITS
CORE_SIGNUP_PER_HOUR=50
EOF
    chmod 600 "$STATE/.env"
    ok "generated .deploy/.env (random admin token)"
  fi

  # Public dashboard config for this local stack. The repository keeps
  # GATEWAY_URL empty so the public site stays honest.
  cat > "$STATE/config.js" <<EOF
/* Generated by ./deploy.sh for the local stack. Not committed. */
window.AE_CONFIG = {
  GATEWAY_URL: "$GATEWAY",
  REPO_URL: "https://github.com/apieverything/core",
  STARTER_CREDITS: $CORE_STARTER_CREDITS,
  COSTS: [
    ["Instagram / TikTok posts", 3],
    ["LinkedIn aggregate signals", 2],
    ["LinkedIn people (blocked)", 5],
    ["Profile / job / company metadata", 1],
  ],
};
EOF
  ok "generated .deploy/config.js -> $GATEWAY"
}

wait_healthy() {
  local url="$1" label="$2"
  for _ in $(seq 1 60); do
    if curl -fsS --max-time 2 "$url" >/dev/null 2>&1; then ok "$label ready"; return 0; fi
    sleep 1
  done
  warn "$label did not become ready in time - check ./deploy.sh logs"
  return 1
}

api_post() {
  local path="$1" body="$2" auth="${3:-}"
  local headers=(-H "Content-Type: application/json")
  [[ -n "$auth" ]] && headers+=(-H "X-Admin-Token: $auth")
  curl -fsS --max-time 10 "${headers[@]}" -d "$body" "$GATEWAY$path" 2>/dev/null || true
}

json_field() {
  node -e '
    let s = "";
    process.stdin.on("data", d => s += d).on("end", () => {
      try { console.log(JSON.parse(s)[process.argv[1]] || ""); } catch { console.log(""); }
    });
  ' "$1"
}

print_urls() {
  printf '\n  %sAPI Everything is up%s\n\n' "$GREEN" "$RST"
  printf '    %-14s %s\n' "Website" "$SITE"
  printf '    %-14s %s\n' "Dashboard" "$SITE/app.html"
  printf '    %-14s %s\n' "Gateway" "$GATEWAY"
  printf '    %-14s %s\n' "Health" "$GATEWAY/health"
  printf '    %-14s %s\n' "API status" "$GATEWAY/v1/status"
  printf '    %-14s %s\n' "OpenAPI" "$GATEWAY/openapi.yaml"
  printf '\n  %sTry it like production:%s\n\n' "$DIM" "$RST"
  printf '    %s\n' "# 1. open $SITE/app.html -> Create my key -> SAVE IT"
  printf '    %s\n' "# 2. or from the CLI:"
  printf '    %s\n' 'KEY=$(./deploy.sh key)'
  printf '    %s\n' "curl \"$GATEWAY/v1/instagram/kametolol/posts?limit=2\" -H \"X-API-Key: \$KEY\""
  printf '    %s\n' "curl \"$GATEWAY/v1/usage\" -H \"X-API-Key: \$KEY\""
  printf '\n  %sAdmin token:%s %s\n' "$DIM" "$RST" "$(admin_token)"
  printf '  %sNo subscription. No monthly reset. Failed requests are never charged.\n' "$DIM"
  printf '  %sConnectors are internal-only - exactly like production.%s\n\n' "$DIM" "$RST"
}

cmd_up() {
  prepare
  info "building and starting the stack..."
  "${COMPOSE[@]}" up -d --build --remove-orphans

  wait_healthy "$GATEWAY/health" "core gateway" || true
  wait_healthy "$SITE/" "website" || true

  local status healthy total
  status="$(curl -fsS --max-time 5 "$GATEWAY/v1/status" 2>/dev/null || true)"
  healthy="$(json_field healthy <<<"$status")"
  total="$(json_field total <<<"$status")"
  healthy="${healthy:-0}"; total="${total:-0}"
  if [[ "$healthy" == "$total" && "$total" != "0" ]]; then
    ok "$healthy/$total connectors healthy"
  else
    warn "$healthy/$total connectors healthy (they may still be warming up)"
  fi

  local code
  code="$(api_post /v1/vouchers '{"credits":500}' "$(admin_token)" | json_field code)"
  if [[ -n "$code" ]]; then
    printf '\n  %sTest voucher:%s %s\n' "$GREEN" "$RST" "$code"
    info "paste it in the dashboard -> Add quota (+500 credits)"
  fi
  print_urls
}

cmd_down() {
  need docker
  info "stopping the stack (key database volume is kept)"
  "${COMPOSE[@]}" down
  ok "stopped"
}

cmd_status() {
  printf '\n'
  for entry in "core gateway|$GATEWAY/health" "website|$SITE/" "api status|$GATEWAY/v1/status"; do
    local label="${entry%%|*}" url="${entry##*|}"
    if curl -fsS --max-time 3 "$url" >/dev/null 2>&1; then ok "$label"; else warn "$label unreachable"; fi
  done
  printf '\n'
  local status
  status="$(curl -fsS --max-time 5 "$GATEWAY/v1/status" 2>/dev/null || true)"
  if [[ -n "$status" ]]; then
    node -e '
      const j = JSON.parse(process.argv[1]);
      for (const c of (j.services || [])) {
        console.log("  " + (c.ok ? "OK  " : "DOWN") + " " + c.service.padEnd(12) + " " + (c.ok ? c.latencyMs + " ms" : "unavailable"));
      }
    ' "$status" || warn "could not parse status"
  else
    warn "status unavailable"
  fi
  printf '\n'
}

# Scriptable: stdout contains ONLY the value. Human messages go to stderr.
cmd_key() {
  local result key
  result="$(api_post /v1/signup '{}')"
  key="$(json_field key <<<"$result")"
  [[ -n "$key" ]] || die "signup failed - is the stack up? (./deploy.sh up)"
  printf '  %sSave this key - shown once, cannot be recovered.%s\n' "$YELLOW" "$RST" >&2
  printf '%s\n' "$key"
}

cmd_voucher() {
  local result code
  result="$(api_post /v1/vouchers '{"credits":500}' "$(admin_token)")"
  code="$(json_field code <<<"$result")"
  [[ -n "$code" ]] || die "could not issue a voucher - is the stack up?"
  printf '%s\n' "$code"
}

cmd_logs() { need docker; "${COMPOSE[@]}" logs -f --tail=80; }

cmd_check() {
  need node
  need bash
  node "$ROOT/scripts/check-workflows.js"
}

case "${1:-up}" in
  up)      cmd_up ;;
  down)    cmd_down ;;
  status)  cmd_status ;;
  key)     cmd_key ;;
  voucher) cmd_voucher ;;
  logs)    cmd_logs ;;
  urls)    print_urls ;;
  check)   cmd_check ;;
  -h|--help) sed -n '2,19p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
  *) die "unknown command '$1'. Try: up | down | status | key | voucher | logs | urls | check" ;;
esac
